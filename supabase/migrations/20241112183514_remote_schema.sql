CREATE OR REPLACE FUNCTION public.update_movie_popularity()
 RETURNS void
 LANGUAGE plpgsql
AS $function$DECLARE
    movie_record RECORD;
    views_yesterday bigint;
    days_since_release float;
    weight_views float := 0.5; -- Weight for views
    weight_release float := 0.3; -- Weight for release date
    weight_current_popularity float := 0.2; -- Weight for current popularity
BEGIN
    FOR movie_record IN 
        SELECT id, release_date, popularity
        FROM public.movies
    LOOP
        -- Get the number of views for the movie from the previous day
        SELECT COUNT(*)
        INTO views_yesterday
        FROM public.views
        WHERE item_id = movie_record.id
          AND item_type = 'movie'
          AND date = CURRENT_DATE - INTERVAL '1 day';

        -- Calculate days since release
        days_since_release := 
            CASE 
                WHEN movie_record.release_date IS NULL THEN 10000::float
                WHEN movie_record.release_date > CURRENT_DATE THEN 10000::float
                ELSE EXTRACT(DAY FROM CURRENT_DATE - movie_record.release_date)::float
            END;

        -- Calculate new popularity
        movie_record.popularity := 
            (views_yesterday::float * weight_views) +
            (1.0 / (1::float + days_since_release) * weight_release) + 
            (movie_record.popularity * weight_current_popularity);

        -- Update the movie's popularity
        UPDATE public.movies
        SET popularity = movie_record.popularity
        WHERE id = movie_record.id;
    END LOOP;
END;$function$
;

