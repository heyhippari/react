CREATE OR REPLACE FUNCTION public.custom_access_token_hook(event jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE
 SET search_path TO ''
AS $function$
  declare
    claims jsonb;
    user_role public.app_role;
  begin
    -- Fetch the user role in the user_roles table
    select role into user_role from public.user_roles where user_id = (event->>'user_id')::uuid;

    claims := event->'claims';

    if user_role is not null then
      -- Set the claim
      claims := jsonb_set(claims, '{user_role}', to_jsonb(user_role));
    else
      claims := jsonb_set(claims, '{user_role}', 'null');
    end if;

    -- Update the 'claims' object in the original event
    event := jsonb_set(event, '{claims}', claims);

    -- Return the modified or original event
    return event;
  end;
$function$
;

create materialized view "public"."movies_fts" as  SELECT m.id,
    m.name,
    m.original_name,
    m.dvd_id,
    m.release_date,
    m.popularity,
    m.create_time,
    s.name AS studio_name,
    s.original_name AS studio_original_name,
    se.name AS series_name,
    se.original_name AS series_original_name,
    l.name AS label_name,
    l.original_name AS label_original_name,
    string_agg(DISTINCT (p.name)::text, ', '::text) AS person_names,
    string_agg(DISTINCT (p.original_name)::text, ', '::text) AS person_original_names,
    (to_tsvector('english'::regconfig, (((((((((((COALESCE(m.name, ''::character varying))::text || ' '::text) || (COALESCE(m.dvd_id, ''::character varying))::text) || ' '::text) || (COALESCE(s.name, ''::character varying))::text) || ' '::text) || (COALESCE(se.name, ''::character varying))::text) || ' '::text) || (COALESCE(l.name, ''::character varying))::text) || ' '::text) || COALESCE(string_agg(DISTINCT (p.name)::text, ', '::text), ''::text))) || to_tsvector('simple'::regconfig, (((((((((COALESCE(m.original_name, ''::character varying))::text || ' '::text) || (COALESCE(s.original_name, ''::character varying))::text) || ' '::text) || (COALESCE(se.original_name, ''::character varying))::text) || ' '::text) || (COALESCE(l.original_name, ''::character varying))::text) || ' '::text) || COALESCE(string_agg(DISTINCT (p.original_name)::text, ', '::text), ''::text)))) AS fts_vector
   FROM (((((movies m
     LEFT JOIN studios s ON ((m.studio_id = s.id)))
     LEFT JOIN series se ON ((m.series_id = se.id)))
     LEFT JOIN labels l ON ((m.label_id = l.id)))
     LEFT JOIN roles r ON ((m.id = r.movie_id)))
     LEFT JOIN persons p ON ((r.person_id = p.id)))
  GROUP BY m.id, s.name, s.original_name, se.name, se.original_name, l.name, l.original_name;


