CREATE OR REPLACE FUNCTION public.search_movies(search_query text, role_age smallint DEFAULT NULL::smallint, sort_by text DEFAULT 'relevance'::text, sort_order text DEFAULT 'DESC'::text)
 RETURNS TABLE(id bigint, name text, original_name text, dvd_id text, release_date timestamp with time zone, front_cover_url text)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY EXECUTE format(
        'SELECT 
            m.id,
            m.name,
            m.original_name,
            m.dvd_id,
            m.release_date,
            m.front_cover_url
        FROM 
            public.movies m
        JOIN 
            public.movies_fts fts ON m.id = fts.id
        LEFT JOIN 
            public.roles r ON m.id = r.movie_id
        WHERE 
            fts.fts_vector @@ to_tsquery(%L)
            AND (%L IS NULL OR r.age = %L)
        ORDER BY 
            CASE 
                WHEN %L = ''popularity'' THEN m.popularity
                WHEN %L = ''create_time'' THEN m.create_time
                WHEN %L = ''dvd_id'' THEN m.dvd_id
                WHEN %L = ''release_date'' THEN m.release_date
                ELSE ts_rank(fts.fts_vector, to_tsquery(%L))
            END 
            COLLATE "C" %s',
        search_query,
        role_age,
        role_age,
        sort_by,
        sort_by,
        sort_by,
        sort_by,
        search_query,
        sort_order
    );
END;
$function$
;

