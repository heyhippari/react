CREATE OR REPLACE FUNCTION public.update_person_popularity()
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    person_record RECORD;
    weight_views float := 0.7;  
    weight_current_popularity float := 0.3;
    total_views BIGINT;
BEGIN
    -- Loop through each person in the persons table
    FOR person_record IN SELECT id FROM public.persons LOOP
        -- Count the number of views for the current person in the previous day
        SELECT COUNT(*) INTO total_views
        FROM public.views
        WHERE item_type = 'person' AND item_id = person_record.id
        AND date = CURRENT_DATE - INTERVAL '1 day';

        -- Update the popularity score based on views and current popularity
        UPDATE public.persons
        SET popularity = (weight_views * total_views::float) + (weight_current_popularity * COALESCE(popularity, 0::float))
        WHERE id = person_record.id;
    END LOOP;
END;
$function$
;

